let language = 'en';
export function getLanguage() { return language; }
export function t(key, params = {}) {
  return (translations[language][key] ?? translations.en[key] ?? translations[language].unexpected)
    .replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ''));
}
export function formatCount(value) {
  return new Intl.NumberFormat(language).format(BigInt(value));
}
const bindings = new Map();
export function setLiteralText(element, value) {
  bindings.delete(element);
  element.textContent = value;
}
export function setText(element, key, params = {}) {
  bindings.set(element, { key, params });
  element.textContent = key ? t(key, params) : '';
}
export function applyLanguage(next, root = document) {
  language = Object.hasOwn(translations, next) ? next : 'en';
  root.documentElement.lang = language;
  root.querySelectorAll('[data-i18n]').forEach(element => {
    element.textContent = t(element.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-aria]').forEach(element => {
    element.setAttribute('aria-label', t(element.dataset.i18nAria));
  });
  root.querySelector('meta[name="description"]').content = t('A public counter shared and updated in real time.');
  for (const [element, { key, params }] of bindings) setText(element, key, params);
}
